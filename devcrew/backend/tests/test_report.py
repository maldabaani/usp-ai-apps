def test_code_search_status_after_a_restart_reads_the_event_log(tmp_path: Path) -> None:
    rag = RagService(FakeChroma, None, Settings(_env_file=None))  # type: ignore[arg-type]

    def event(i: int, type: EventType, **payload: Any) -> Event:
        return Event(id=i, run_id="r", type=type, payload=payload)

    ok = event(1, EventType.TOOL_RESULT, tool="index_codebase", ok=True)
    failed = event(2, EventType.ERROR, message="indexing failed: timeout")
    assert code_search_status(rag, "r", []).status == "pending"
    assert code_search_status(rag, "r", [ok]).status == "ok"
    status = code_search_status(rag, "r", [ok, failed])
    assert status.status == "unavailable" and status.detail == "indexing failed: timeout"
    assert code_search_status(rag, "r", [failed, ok]).status == "ok"
